#!/usr/bin/env bash
# Deploys QRforQA to the production server.
#
# The server is a clean Debian box: no Go, no Node, no nginx, no docker. It
# needs none of them, because the frontend is embedded in a static Go binary
# and nothing is fetched from the network at run time. That matters here — the
# server is in China and cannot reliably reach GitHub or npm.
#
# Usage:
#   SSHPASS='...' ./scripts/deploy.sh
#
# Environment:
#   DEPLOY_HOST    target hostname or IP (required)
#   DEPLOY_PORT    SSH port, default 22
#   DEPLOY_USER    SSH user, default root
#   SSHPASS        SSH password; omit to use key-based auth
#   SKIP_BUILD     set to 1 to reuse dist/qrforqa-linux-amd64
#   SKIP_SMOKE     set to 1 to skip the post-deploy verification
#
# Example:
#   DEPLOY_HOST=example.com DEPLOY_PORT=2222 SSHPASS='…' ./scripts/deploy.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

HOST="${DEPLOY_HOST:-}"
PORT="${DEPLOY_PORT:-22}"
USER="${DEPLOY_USER:-root}"
BIN="dist/qrforqa-linux-amd64"

if [[ -z "$HOST" ]]; then
  echo "DEPLOY_HOST is required, e.g. DEPLOY_HOST=example.com $0" >&2
  echo "For a one-command install that runs on the target host itself, use deploy/install.sh instead." >&2
  exit 2
fi

SSH_OPTS=(-p "$PORT" -o StrictHostKeyChecking=accept-new -o ConnectTimeout=20)
if [[ -n "${SSHPASS:-}" ]]; then
  SSH=(sshpass -e ssh "${SSH_OPTS[@]}")
  SCP=(sshpass -e scp -P "$PORT" -o StrictHostKeyChecking=accept-new)
else
  echo "SSHPASS is not set; falling back to key-based auth." >&2
  SSH=(ssh "${SSH_OPTS[@]}")
  SCP=(scp -P "$PORT" -o StrictHostKeyChecking=accept-new)
fi

remote() { "${SSH[@]}" "$USER@$HOST" "$@"; }

step() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }

# ------------------------------------------------------------------ build ----
if [[ "${SKIP_BUILD:-0}" != "1" ]]; then
  step "verifying codec conformance before building"
  ./scripts/conformance.sh

  step "building the frontend"
  (cd frontend && npm ci --no-audit --no-fund && npm run build)

  step "cross-compiling a static linux/amd64 binary"
  mkdir -p dist
  (cd backend && CGO_ENABLED=0 GOOS=linux GOARCH=amd64 go build \
    -trimpath -tags 'netgo osusergo' \
    -ldflags "-s -w -X main.version=$(git describe --tags --always --dirty 2>/dev/null || echo dev) -X main.commit=$(git rev-parse --short HEAD 2>/dev/null || echo none)" \
    -o "../$BIN" ./cmd/server)
  ls -lh "$BIN"
fi

[[ -f "$BIN" ]] || { echo "missing $BIN" >&2; exit 1; }

step "running the codec self-test against the binary we are about to ship"
if file "$BIN" | grep -q "ELF"; then
  echo "    (linux binary; self-test runs on the server after upload)"
else
  "$BIN" selftest
fi

# ------------------------------------------------------------------ upload ---
step "uploading to $USER@$HOST:$PORT"
remote "mkdir -p /opt/qrforqa/data /etc/qrforqa"
"${SCP[@]}" "$BIN" "$USER@$HOST:/usr/local/bin/qrforqa.new"
"${SCP[@]}" deploy/qrforqa.service "$USER@$HOST:/etc/systemd/system/qrforqa.service"

step "creating the service account, secrets and database directory"
remote bash -s <<'REMOTE'
set -euo pipefail

# A dedicated, unprivileged account. The unit grants it only CAP_NET_BIND_SERVICE
# so it can bind port 80 without ever running as root.
if ! id -u qrforqa >/dev/null 2>&1; then
  useradd --system --home /opt/qrforqa --shell /usr/sbin/nologin qrforqa
fi
mkdir -p /opt/qrforqa/data /etc/qrforqa
chown -R qrforqa:qrforqa /opt/qrforqa
chmod 750 /opt/qrforqa /opt/qrforqa/data
chmod 700 /etc/qrforqa

ENV_FILE=/etc/qrforqa/qrforqa.env
FRESH=0
if [[ ! -f "$ENV_FILE" ]]; then
  FRESH=1
  MASTER=$(/usr/local/bin/qrforqa.new keygen)
  JWT=$(/usr/local/bin/qrforqa.new keygen)
  ADMIN_PW=$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | head -c 20)
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/install on $(date -Iseconds).
# KEEP A BACKUP OF QRFORQA_MASTER_KEY: without it every stored
# questionnaire and response becomes permanently unreadable.
QRFORQA_MASTER_KEY=$MASTER
QRFORQA_JWT_SECRET=$JWT
QRFORQA_ADMIN_USER=admin
QRFORQA_ADMIN_PASSWORD=$ADMIN_PW

QRFORQA_ADDR=:3388
QRFORQA_ALT_ADDR=:3389
QRFORQA_DATA_DIR=/opt/qrforqa/data
QRFORQA_DB=/opt/qrforqa/data/qrforqa.db
QRFORQA_LAYOUT=ascii
QRFORQA_TOKEN_TTL=12h
QRFORQA_MAX_UPLOAD_BYTES=2097152
QRFORQA_DEV=0
EOF
fi
chmod 600 "$ENV_FILE"
chown root:root "$ENV_FILE"

install -m 0755 -o root -g root /usr/local/bin/qrforqa.new /usr/local/bin/qrforqa
rm -f /usr/local/bin/qrforqa.new

/usr/local/bin/qrforqa selftest

systemctl daemon-reload
systemctl enable qrforqa
systemctl restart qrforqa
sleep 3
systemctl is-active qrforqa

if [[ "$FRESH" == "1" ]]; then
  echo
  echo "FIRST INSTALL — record these now:"
  echo "  admin username: admin"
  echo "  admin password: $(grep '^QRFORQA_ADMIN_PASSWORD=' "$ENV_FILE" | cut -d= -f2-)"
  echo "  master key:     $(grep '^QRFORQA_MASTER_KEY=' "$ENV_FILE" | cut -d= -f2-)"
  echo "  (also in $ENV_FILE, mode 0600)"
fi
REMOTE

# ------------------------------------------------------------------- smoke ---
if [[ "${SKIP_SMOKE:-0}" != "1" ]]; then
  step "verifying the deployment end to end"
  # Read the credentials the way the service does, without ever printing the
  # master key.
  ADMIN_PW=$(remote "grep '^QRFORQA_ADMIN_PASSWORD=' /etc/qrforqa/qrforqa.env | cut -d= -f2-")
  BASE_URL="http://$HOST" QRFORQA_ADMIN_PASSWORD="$ADMIN_PW" python3 scripts/smoke.py "http://$HOST"

  step "service log (last 20 lines)"
  remote "journalctl -u qrforqa -n 20 --no-pager"
fi

printf '\n\033[32mdeployed\033[0m — http://%s\n' "$HOST"
