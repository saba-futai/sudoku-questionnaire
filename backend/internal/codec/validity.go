package codec

import (
	"fmt"
	"math/bits"
)

const (
	// validityRowBytes is the number of bytes needed for 1820 bits.
	validityRowBytes = (PosSetCount + 7) / 8 // 228
	// ValidityBytes is the size of the whole bitmap: one row per grid.
	ValidityBytes = GridCount * validityRowBytes // 65664
)

// Group encodes a single clue as a 6-bit value: the cell's digit (0..3, i.e.
// digit-1) in bits 4-5 and the cell position (0..15) in bits 0-3.
//
// Storing digit AND position in one 6-bit symbol is what makes a puzzle's
// identity independent of the byte layout: the layout only decides which wire
// byte each group becomes. See spec/CODEC.md §1.5.
func Group(digit, pos byte) byte { return (digit << 4) | (pos & 0x0F) }

// groupOfGrid returns the group for grid g at cell pos.
func groupOfGrid(g *Grid, pos byte) byte { return Group(g[pos]-1, pos) }

// PackGroups sorts four groups ascending and packs them into 24 bits.
//
// Sorting makes the decode key order-independent, which is exactly what buys
// the encoder its freedom to emit the four clue bytes in any of 24
// permutations. Packing as 6-bit fields (rather than the raw wire bytes) keeps
// the result under 2^31 so the TypeScript mirror never sees a negative value
// from `a << 24`. See spec/CODEC.md §1.5.
func PackGroups(gr [4]byte) uint32 {
	a, b, c, d := gr[0], gr[1], gr[2], gr[3]
	// 5-comparator sorting network: branch-free and identical in both languages.
	if a > b {
		a, b = b, a
	}
	if c > d {
		c, d = d, c
	}
	if a > c {
		a, c = c, a
	}
	if b > d {
		b, d = d, b
	}
	if b > c {
		b, c = c, b
	}
	return uint32(a)<<18 | uint32(b)<<12 | uint32(c)<<6 | uint32(d)
}

// SortGroups sorts four groups ascending in place.
func SortGroups(gr *[4]byte) {
	a, b, c, d := gr[0], gr[1], gr[2], gr[3]
	if a > b {
		a, b = b, a
	}
	if c > d {
		c, d = d, c
	}
	if a > c {
		a, c = c, a
	}
	if b > d {
		b, d = d, b
	}
	if b > c {
		b, c = c, b
	}
	gr[0], gr[1], gr[2], gr[3] = a, b, c, d
}

// Validity records, for every (grid, position set) pair, whether that set of
// four clues uniquely identifies that grid among all 288.
//
// Key insight: this is independent of the encryption key. It depends only on
// the grid enumeration and the position-set enumeration, both fixed constants.
// A byte's valid encodings are therefore inherited from the grid it is mapped
// to, so the expensive 524,160-signature computation is a build-time artifact
// rather than per-questionnaire work. See spec/CODEC.md §1.1.
type Validity struct {
	rowBytes int
	bits     []byte
}

// Valid reports whether position set p uniquely identifies grid g.
func (v *Validity) Valid(g, p int) bool {
	return v.bits[g*v.rowBytes+p/8]&(1<<uint(p%8)) != 0
}

// Bytes exposes the raw bitmap for hashing, embedding and shipping.
func (v *Validity) Bytes() []byte { return v.bits }

// EncodeCount returns how many position sets are valid for grid g.
func (v *Validity) EncodeCount(g int) int {
	n := 0
	row := v.bits[g*v.rowBytes : (g+1)*v.rowBytes]
	for _, b := range row {
		n += bits.OnesCount8(b)
	}
	return n
}

// Counts returns the per-grid encode count for all 288 grids.
func (v *Validity) Counts() []int {
	out := make([]int, GridCount)
	for g := 0; g < GridCount; g++ {
		out[g] = v.EncodeCount(g)
	}
	return out
}

// ComputeValidity derives the bitmap from scratch.
//
// This is the reference implementation: the shipped bitmap is generated by it
// and a test asserts the two agree, so a corrupted or stale artifact cannot
// reach production. The TypeScript side implements the same function for the
// same reason.
func ComputeValidity() *Validity {
	grids := Grids()
	pos := PosSets()

	// Pass 1: how many (grid, positions) triples share each signature.
	// A signature is unique to exactly one grid iff this count is 1.
	counts := make(map[uint32]int, GridCount*PosSetCount)
	var gr [4]byte
	for gi := range grids {
		g := &grids[gi]
		for _, p := range pos {
			for i := 0; i < 4; i++ {
				gr[i] = groupOfGrid(g, p[i])
			}
			counts[PackGroups(gr)]++
		}
	}

	// Pass 2: record the uniquely-identifying position sets.
	v := &Validity{rowBytes: validityRowBytes, bits: make([]byte, ValidityBytes)}
	for gi := range grids {
		g := &grids[gi]
		for pi, p := range pos {
			for i := 0; i < 4; i++ {
				gr[i] = groupOfGrid(g, p[i])
			}
			if counts[PackGroups(gr)] == 1 {
				v.bits[gi*validityRowBytes+pi/8] |= 1 << uint(pi%8)
			}
		}
	}
	return v
}

// LoadValidity wraps a serialised bitmap, rejecting wrong-sized input so a
// truncated or stale artifact fails loudly instead of producing a table that
// only decodes some inputs.
func LoadValidity(b []byte) (*Validity, error) {
	if len(b) != ValidityBytes {
		return nil, fmt.Errorf("validity bitmap: got %d bytes, want %d", len(b), ValidityBytes)
	}
	return &Validity{rowBytes: validityRowBytes, bits: b}, nil
}
