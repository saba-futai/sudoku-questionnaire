#!/usr/bin/env bash
#
# One-click installer for Sudoku Questionnaire.
#
# Run from a clone of the repository on the machine that will host it:
#
#     sudo ./deploy/install.sh
#
# Defaults to ports 3388 (everything) and 3389 (a second listener), so the
# service never collides with a web server already holding port 80.
#
# Options:
#   --addr <addr>        primary listener            (default :3388)
#   --alt-addr <addr>    second listener, "" to skip (default :3389)
#   --binary <path>      use a prebuilt linux binary instead of compiling
#   --user <name>        service account name        (default qrforqa)
#   --skip-build         reuse an existing dist/ binary
#
# Environment overrides for the generated config: QRFORQA_ADMIN_USER.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

ADDR=":3388"
ALT_ADDR=":3389"
SERVICE_USER="qrforqa"
BINARY=""
SKIP_BUILD=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --addr)       ADDR="$2"; shift 2 ;;
    --alt-addr)   ALT_ADDR="$2"; shift 2 ;;
    --binary)     BINARY="$2"; shift 2 ;;
    --user)       SERVICE_USER="$2"; shift 2 ;;
    --skip-build) SKIP_BUILD=1; shift ;;
    -h|--help)    sed -n '2,21p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

ENV_DIR=/etc/qrforqa
ENV_FILE="$ENV_DIR/qrforqa.env"
DATA_DIR=/opt/qrforqa
BIN_PATH=/usr/local/bin/qrforqa
UNIT_PATH=/etc/systemd/system/qrforqa.service

step() { printf '\n\033[1m==> %s\033[0m\n' "$1"; }
die()  { printf '\033[31merror:\033[0m %s\n' "$1" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "must run as root (try: sudo $0)"
[[ -f "$REPO_ROOT/deploy/qrforqa.service" ]] || die "run this from a clone of the repository"

# --------------------------------------------------------------- binary ----
if [[ -z "$BINARY" && $SKIP_BUILD -eq 0 && ! -f "$REPO_ROOT/dist/qrforqa-linux-amd64" ]]; then
  step "building from source"

  command -v go >/dev/null 2>&1 || die "Go is required to build (or pass --binary /path/to/binary)"
  command -v node >/dev/null 2>&1 || die "Node is required to build the frontend (or pass --binary)"

  ( cd "$REPO_ROOT/frontend" && npm ci --no-audit --no-fund && npm run build )
  ( cd "$REPO_ROOT/backend" && CGO_ENABLED=0 GOOS=linux GOARCH=amd64 go build \
      -trimpath -tags 'netgo osusergo' -ldflags "-s -w" \
      -o "$REPO_ROOT/dist/qrforqa-linux-amd64" ./cmd/server )
fi

BINARY="${BINARY:-$REPO_ROOT/dist/qrforqa-linux-amd64}"
[[ -f "$BINARY" ]] || die "no binary at $BINARY (build first, or pass --binary)"
[[ "$(uname -s)" == "Linux" ]] || die "this installer targets Linux (cross-compile, then run it on the host)"

step "verifying the codec before installing"
"$BINARY" selftest

# --------------------------------------------------------------- layout ----
step "creating the service account and directories"
if ! id -u "$SERVICE_USER" >/dev/null 2>&1; then
  useradd --system --home "$DATA_DIR" --shell /usr/sbin/nologin "$SERVICE_USER"
fi
mkdir -p "$DATA_DIR/data" "$ENV_DIR"
chown -R "$SERVICE_USER:$SERVICE_USER" "$DATA_DIR"
chmod 750 "$DATA_DIR" "$DATA_DIR/data"
chmod 700 "$ENV_DIR"

# ---------------------------------------------------------------- secrets --
step "configuring"
FRESH=0
if [[ ! -f "$ENV_FILE" ]]; then
  FRESH=1
  MASTER_KEY="$("$BINARY" keygen)"
  JWT_SECRET="$("$BINARY" keygen)"
  ADMIN_PASSWORD="$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | head -c 20)"
  ADMIN_USER="${QRFORQA_ADMIN_USER:-admin}"

  cat > "$ENV_FILE" <<EOF
# Generated by deploy/install.sh on $(date -Iseconds).
#
# KEEP A BACKUP OF QRFORQA_MASTER_KEY. It derives every questionnaire's
# mapping table; without it every stored answer becomes unreadable.
QRFORQA_MASTER_KEY=$MASTER_KEY
QRFORQA_JWT_SECRET=$JWT_SECRET
QRFORQA_ADMIN_USER=$ADMIN_USER
QRFORQA_ADMIN_PASSWORD=$ADMIN_PASSWORD

# Everything — the API and the frontend — is served on this port.
QRFORQA_ADDR=$ADDR
# Optional second listener. Set empty to disable.
QRFORQA_ALT_ADDR=$ALT_ADDR

QRFORQA_DATA_DIR=$DATA_DIR/data
QRFORQA_DB=$DATA_DIR/data/qrforqa.db
QRFORQA_LAYOUT=ascii
QRFORQA_TOKEN_TTL=12h
QRFORQA_MAX_UPLOAD_BYTES=2097152
QRFORQA_DEV=0
EOF
else
  echo "    $ENV_FILE already exists; leaving it untouched"
fi
chmod 600 "$ENV_FILE"
chown root:root "$ENV_FILE"

# Whatever is actually configured wins. Re-running the installer against an
# existing installation must verify the port that installation uses, not the
# port this script would have picked for a fresh one.
ADDR="$(sed -n 's/^QRFORQA_ADDR=//p' "$ENV_FILE" | tail -1)"
ALT_ADDR="$(sed -n 's/^QRFORQA_ALT_ADDR=//p' "$ENV_FILE" | tail -1)"
[[ -n "$ADDR" ]] || die "QRFORQA_ADDR is missing from $ENV_FILE"

# The unit file names its own user, so rewrite it when --user was overridden.
sed "s/^User=.*/User=$SERVICE_USER/; s/^Group=.*/Group=$SERVICE_USER/" \
  "$REPO_ROOT/deploy/qrforqa.service" > "$UNIT_PATH"
sed -i "s#^ReadWritePaths=.*#ReadWritePaths=$DATA_DIR#" "$UNIT_PATH"

# ---------------------------------------------------------------- install --
step "installing the binary and service unit"
install -m 0755 -o root -g root "$BINARY" "$BIN_PATH"
systemctl daemon-reload
systemctl enable qrforqa >/dev/null
systemctl restart qrforqa
sleep 2

if ! systemctl is-active --quiet qrforqa; then
  echo
  echo "the service failed to start; last log lines:" >&2
  journalctl -u qrforqa -n 30 --no-pager >&2
  exit 1
fi

# --------------------------------------------------------------- verify ----
step "verifying"
HEALTH_PORT="${ADDR##*:}"
HEALTHY=0
for _ in $(seq 1 10); do
  if curl -fsS -m 3 "http://127.0.0.1:$HEALTH_PORT/healthz" >/dev/null 2>&1; then
    HEALTHY=1
    break
  fi
  sleep 1
done

if [[ $HEALTHY -eq 1 ]]; then
  curl -fsS -m 5 "http://127.0.0.1:$HEALTH_PORT/healthz" | head -c 220; echo
else
  echo "the service is running but http://127.0.0.1:$HEALTH_PORT/healthz did not answer." >&2
  echo "most likely the port is below 1024 and something else already holds it," >&2
  echo "or the port is blocked. Re-run with a different port, e.g. --addr :3388" >&2
  echo >&2
  journalctl -u qrforqa -n 20 --no-pager >&2
  exit 1
fi

# ---------------------------------------------------------------- report ---
step "done"
HOST_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
PORT="${ADDR##*:}"
echo "  URL          http://${HOST_IP:-<host>}:$PORT"
echo "  config       $ENV_FILE  (mode 0600, root-owned)"
echo "  data         $DATA_DIR/data"
echo "  service      systemctl status qrforqa"

if [[ "$FRESH" == "1" ]]; then
  echo
  echo "  ┌─────────────────────── ADMIN CREDENTIALS ───────────────────────┐"
  printf "  │ username: %-52s │\n" "$ADMIN_USER"
  printf "  │ password: %-52s │\n" "$ADMIN_PASSWORD"
  echo "  └─────────────────────────────────────────────────────────────────┘"
  echo "  Shown once. Also stored in $ENV_FILE."
  echo
  echo "  Back up QRFORQA_MASTER_KEY now — without it the database cannot be read."
fi

echo
echo "If a firewall is active, allow the ports:"
echo "  ufw allow $PORT/tcp$([[ -n "$ALT_ADDR" ]] && echo " && ufw allow ${ALT_ADDR##*:}/tcp")"
echo "…and open them in your cloud provider's security group."
